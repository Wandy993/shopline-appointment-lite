import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const themeDir = path.resolve(process.argv[2] || path.join(root, 'theme-app-extension'));
const publicDir = path.join(themeDir, 'public');

// SHOPLINE Theme Extension public assets support TTF/WOFF fonts. The CLI rejects WOFF2.
// Use the Expo Google Fonts npm packages as a pinned, local TTF source and copy only
// the exact weights used by customer-facing Theme Extension UI.
const files = [
  ['@expo-google-fonts/jost/600SemiBold/Jost_600SemiBold.ttf', 'al-jost-600.ttf'],
  ['@expo-google-fonts/poppins/400Regular/Poppins_400Regular.ttf', 'al-poppins-400.ttf'],
  ['@expo-google-fonts/poppins/500Medium/Poppins_500Medium.ttf', 'al-poppins-500.ttf'],
  ['@expo-google-fonts/poppins/600SemiBold/Poppins_600SemiBold.ttf', 'al-poppins-600.ttf'],
  ['@expo-google-fonts/poppins/700Bold/Poppins_700Bold.ttf', 'al-poppins-700.ttf']
];

fs.mkdirSync(publicDir, { recursive: true });

// Always remove fonts generated by older releases before validation/push.
for (const name of fs.readdirSync(publicDir)) {
  if (/^al-(?:jost|poppins)-.*\.(?:woff2|woff|ttf)$/i.test(name)) {
    fs.rmSync(path.join(publicDir, name), { force: true });
  }
}

for (const [modulePath, targetName] of files) {
  const source = path.join(root, 'node_modules', modulePath);
  const target = path.join(publicDir, targetName);
  if (!fs.existsSync(source)) {
    console.error(`customer-font-sync: missing ${source}`);
    console.error('Run npm install before syncing the Theme Extension.');
    process.exit(1);
  }
  fs.copyFileSync(source, target);
}

const unsupported = fs.readdirSync(publicDir).filter(name => /^al-(?:jost|poppins)-.*\.woff2$/i.test(name));
if (unsupported.length) {
  console.error(`customer-font-sync: unsupported SHOPLINE WOFF2 assets remain: ${unsupported.join(', ')}`);
  process.exit(1);
}

console.log(`customer-font-sync: OK (${files.length} SHOPLINE-compatible TTF assets -> ${publicDir})`);
